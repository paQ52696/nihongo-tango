// 說明、例句、題目都是自行撰寫（不是課本內容），題型模仿 N5「文法」：（　）選擇與 ★ 排序。

export interface GrammarQuestion {
  stem: string
  answer: string
  options: string[] // 含正解
  explain?: string
}

export interface GrammarPoint {
  id: string
  lesson: string
  pattern: string
  meaning: string
  explanation: string
  examples: { ja: string; zh: string }[]
  questions: GrammarQuestion[]
}

export interface GrammarSet {
  id: string
  name: string
  points: GrammarPoint[]
}

/** 選擇題：正解＋干擾選項 */
const q = (stem: string, answer: string, wrong: string[], explain?: string): GrammarQuestion => ({ stem, answer, options: [answer, ...wrong], explain })

/** ★ 排序題：parts 依正確順序，star 是 ★ 的位置（從 0 起算） */
const star = (before: string, parts: string[], starAt: number, after = '', explain?: string): GrammarQuestion => {
  const slots = parts.map((_, i) => (i === starAt ? '★' : '＿＿')).join(' ')
  return {
    stem: `${before} ${slots} ${after}`.trim() + '\n（排出正確順序，選出放在 ★ 的詞）',
    answer: parts[starAt],
    options: [parts[starAt], ...parts.filter((_, i) => i !== starAt)],
    explain: explain ?? '正確順序：' + before + parts.join('') + after,
  }
}

