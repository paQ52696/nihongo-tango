export const GRAMMAR_SETS: GrammarSet[] = [{ id: 'minna-13-16', name: '大家的日本語 第13–16課 文法', points: MINNA_13_16 }]

const BY_ID = new Map(GRAMMAR_SETS.flatMap((s) => s.points.map((p) => [p.id, p] as const)))

export function grammarPoint(id: string | undefined): GrammarPoint | undefined {
  return id ? BY_ID.get(id) : undefined
}
